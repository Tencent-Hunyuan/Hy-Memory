const embeddingSwitchKeys = Object.keys(
  embeddingSwitchEnglishMessages,
) as (keyof EmbeddingSwitchMessages)[];

const localized = (values: readonly string[]): EmbeddingSwitchMessages => {
  if (values.length !== embeddingSwitchKeys.length)
    throw new Error(
      `Expected ${embeddingSwitchKeys.length} embedding switch messages, got ${values.length}`,
    );
  return Object.fromEntries(
    embeddingSwitchKeys.map((key, index) => [key, values[index]]),
  ) as EmbeddingSwitchMessages;
};

